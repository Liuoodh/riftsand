/**
 * Art importer.
 *
 *   art/units/*.png + art/manifest*.json
 *     → project/assets/resources/art/**
 *
 * Cocos only bundles a PNG if it lives under `assets/resources` (or an explicitly
 * referenced bundle), and level/unit data has to be available synchronously when
 * a match starts. So the artist keeps working in `art/` at the repo root and this
 * script mirrors the result into the engine:
 *
 *   1. merge every `art/manifest*.json` into one runtime manifest
 *   2. copy each referenced image into `resources/` at the same relative path
 *   3. report atlases whose frame count does not match the PNG size
 *
 * Run it after a Blender batch (`tools/blender/bridge.py run ...`) and before
 * `CocosCreator --build`.
 *
 * usage: node tools/artimport.mjs
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync, copyFileSync, existsSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';

const ROOT = '.';
const ART = 'art';
const OUT = 'project/assets/resources/art';

function pngSize(path) {
    const b = readFileSync(path);
    if (b.readUInt32BE(0) !== 0x89504e47) return null;
    return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
}

/* ---------- merge manifests ---------- */
// art/manifest.example.json is documentation, not a batch
const files = readdirSync(ART).filter((f) => f.startsWith('manifest') && f.endsWith('.json') && !f.includes('example'));
if (!files.length) {
    console.error('no art/manifest*.json found');
    process.exit(1);
}

const merged = { version: 1, note: 'generated by tools/artimport.mjs — do not hand-edit', units: {}, buildings: {} };
const sources = {};
for (const f of files) {
    const doc = JSON.parse(readFileSync(join(ART, f), 'utf8'));
    for (const group of ['units', 'buildings']) {
        for (const [id, def] of Object.entries(doc[group] ?? {})) {
            /*
             * Templates are blank placeholder plates under art/templates — they
             * exist so an artist has the right canvas to paint on. Importing them
             * would overwrite working procedural art with empty frames, so they
             * are skipped until their image is replaced by a real render.
             */
            const img = String(def.image ?? '');
            if (img.includes('/templates/') || img.includes('\\templates\\')) {
                console.log(`skip ${group}/${id}: still a blank template (${img})`);
                continue;
            }
            merged[group][id] = def;
            sources[id] = f;
        }
    }
}

/* ---------- validate + copy ---------- */
mkdirSync(OUT, { recursive: true });
let copied = 0;
const problems = [];

function handle(id, def, group) {
    const images = [];
    if (def.image) images.push(def.image);
    if (def.turret?.image) images.push(def.turret.image);
    for (const rel of images) {
        if (!existsSync(rel)) { problems.push(`${id}: missing image ${rel}`); continue; }
        const dst = join(OUT, rel.replace(/^art\//, ''));
        mkdirSync(dirname(dst), { recursive: true });
        copyFileSync(rel, dst);
        copied++;
    }
    if (!def.image || !existsSync(def.image)) return;
    const size = pngSize(def.image);
    if (!size) { problems.push(`${id}: ${def.image} is not a PNG`); return; }
    const fw = def.frame?.w ?? 72, fh = def.frame?.h ?? 72;
    const cols = Math.floor(size.w / fw), rows = Math.floor(size.h / fh);
    const total = cols * rows;
    const seqs = def.sequences ?? {};
    let need = 0;
    for (const s of Object.values(seqs)) need = Math.max(need, (s.start ?? 0) + (s.frames ?? 0));
    if (def.turret) need = Math.max(need, def.turret.start ?? 0);
    if (need > total) {
        problems.push(`${id}: needs ${need} frames but ${size.w}x${size.h} at ${fw}x${fh} holds ${total}`);
    }
    const stray = size.w % fw;
    if (stray) problems.push(`${id}: width ${size.w} is not a multiple of ${fw}`);
    const strayH = size.h % fh;
    if (strayH) problems.push(`${id}: height ${size.h} is not a multiple of ${fh}`);
    console.log(`ok   ${group}/${id}  ${size.w}x${size.h}  ${cols}x${rows}=${total} frames  (${sources[id]})`);
}

for (const [id, def] of Object.entries(merged.units)) handle(id, def, 'units');
for (const [id, def] of Object.entries(merged.buildings)) handle(id, def, 'units');

writeFileSync(join(OUT, 'manifest.json'), JSON.stringify(merged, null, 2));
console.log(`\nmanifest: ${Object.keys(merged.units).length} units, ${Object.keys(merged.buildings).length} buildings`);
console.log(`copied ${copied} image(s) → ${OUT}`);

if (problems.length) {
    console.error('\nproblems:');
    for (const p of problems) console.error('  - ' + p);
    process.exit(1);
}
void basename; void ROOT;
